// Writes the Dart copies of shared data so the mobile app, web and API agree:
//   shared/skillTaxonomy.js  → flutter_app/lib/core/skill_taxonomy_data.dart
//   shared/emailDomains.js   → flutter_app/lib/core/email_domains.dart
import fs from 'fs';
import path from 'path';
import { FIELDS, PROGRAMS, DEFAULT_FIELD_ID } from '../shared/skillTaxonomy.js';
import { FREE_EMAIL_DOMAINS, DISPOSABLE_DOMAINS, ACADEMIC_DOMAIN } from '../shared/emailDomains.js';

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const list = (items) => `[${items.map(q).join(', ')}]`;

const families = FIELDS.map((f) => `  FieldFamily(
    ${q(f.id)},
    ${q(f.label)},
    [
${f.axes.map((a) => `      SkillAxis(${q(a.name)}, ${list(a.keywords)}),`).join('\n')}
    ],
    [${f.benchmark.join(', ')}],
    {${Object.entries(f.legacyMap).map(([k, v]) => `${q(k)}: ${q(v)}`).join(', ')}},
  ),`).join('\n');

const programs = PROGRAMS.map((p) => `  Program(${q(p.id)}, ${q(p.label)}, ${q(p.family)}, ${list(p.aliases)}),`).join('\n');

const out = `// GENERATED by scripts/gen-taxonomy-dart.mjs from shared/skillTaxonomy.js.
// Do not edit by hand — run \`npm run gen:taxonomy\`.
part of 'skill_taxonomy.dart';

const String kDefaultFieldId = ${q(DEFAULT_FIELD_ID)};

const List<FieldFamily> kFieldFamilies = [
${families}
];

const List<Program> kPrograms = [
${programs}
];
`;
const target = path.resolve('flutter_app/lib/core/skill_taxonomy_data.dart');
fs.writeFileSync(target, out);
console.log(`Wrote ${path.relative(process.cwd(), target)} (${FIELDS.length} families, ${PROGRAMS.length} programmes)`);

const emailOut = `// GENERATED by scripts/gen-taxonomy-dart.mjs from shared/emailDomains.js.
// Do not edit by hand — run \`npm run gen:taxonomy\`.

enum EmailKind { invalid, disposable, personal, nonAcademic, academic, corporate }

class EmailInfo {
  final String domain;
  final EmailKind kind;
  const EmailInfo(this.domain, this.kind);
  bool get institutional => kind == EmailKind.academic || kind == EmailKind.corporate;
}

const Set<String> kFreeEmailDomains = {${[...FREE_EMAIL_DOMAINS].map(q).join(', ')}};
const Set<String> kDisposableDomains = {${[...DISPOSABLE_DOMAINS].map(q).join(', ')}};
final RegExp kAcademicDomain = RegExp(r'${ACADEMIC_DOMAIN.source}', caseSensitive: false);

/// Mirrors classifyEmail() in shared/emailDomains.js. The server is authoritative.
EmailInfo classifyEmail(String email, String role) {
  final parts = email.trim().toLowerCase().split('@');
  final domain = parts.length == 2 ? parts[1] : '';
  if (domain.isEmpty || !domain.contains('.')) return EmailInfo(domain, EmailKind.invalid);
  if (kDisposableDomains.contains(domain)) return EmailInfo(domain, EmailKind.disposable);
  if (kFreeEmailDomains.contains(domain)) return EmailInfo(domain, EmailKind.personal);
  if (role == 'admin' && !kAcademicDomain.hasMatch(domain)) return EmailInfo(domain, EmailKind.nonAcademic);
  return EmailInfo(domain, role == 'admin' ? EmailKind.academic : EmailKind.corporate);
}
`;
const emailTarget = path.resolve('flutter_app/lib/core/email_domains.dart');
fs.writeFileSync(emailTarget, emailOut);
console.log(`Wrote ${path.relative(process.cwd(), emailTarget)}`);
